#!/usr/bin/env python3
"""Prints src/renderer/src/lib/unicodeWidthTable.ts: the cell widths of the C library's wcwidth (glibc), as ranges.

tmux measures characters with wcwidth (or utf8proc), so the app's terminal must agree with it on which characters
take 0 or 2 cells, or every emoji shifts the rest of its line. Run on a recent glibc:
    python3 scripts/unicode-widths.py > src/renderer/src/lib/unicodeWidthTable.ts && npx prettier --write <that file>
"""
import ctypes
import ctypes.util
import platform

libc = ctypes.CDLL(ctypes.util.find_library('c'))
libc.setlocale.restype = ctypes.c_char_p
assert libc.setlocale(6, b'C.UTF-8'), 'no C.UTF-8 locale'
libc.wcwidth.argtypes = [ctypes.c_wchar]


def ranges(width):
    out, start = [], None
    for cp in range(0x20, 0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            hit = False
        else:
            hit = libc.wcwidth(chr(cp)) == width
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, doc, rs):
    flat = ', '.join(f'0x{a:x}, 0x{b:x}' for a, b in rs)
    print(f'/** {doc} */')
    print(f'export const {name} = [{flat}]')


print(f'// Generated by scripts/unicode-widths.py from {platform.libc_ver()[0]} {platform.libc_ver()[1]} wcwidth. Do not edit.')
print('// Inclusive ranges, flattened: [first, last, first, last, ...], sorted.')
print()
emit('ZERO_WIDTH', 'Code points that take no cell (combining marks, joiners, variation selectors).', ranges(0))
print()
emit('WIDE', 'Code points that take two cells (CJK, most emoji).', ranges(2))
